export function createCapabilityManifest(): CapabilityManifest[] {
  const skills: CapabilityManifest[] = CLAW_SKILLS.map(skill => ({
    id: `skill-${skill.id}`,
    kind: 'skill',
    name: skill.name,
    status: 'built-in',
    trigger: skill.trigger,
    purpose: skill.purpose,
    autonomy: skill.id === 'browser-research' || skill.id === 'skill-authoring'
      ? 'approval-required'
      : 'automatic',
    inputs: ['context graph', 'evidence ledger'],
    outputs: skill.outputs,
    safety: ['trigger-scoped loading', 'explicit output contract'],
    installable: skill.id === 'skill-authoring',
  }))

  const models: CapabilityManifest[] = CLAW_MODELS.map(model => ({
    id: `model-${model.id}`,
    kind: 'model',
    name: model.label,
    status: model.enabled ? 'available' : 'planned',
    trigger: model.switchPolicy,
    purpose: `Route ${model.role} work to a configured ${model.provider} model profile.`,
    autonomy: 'automatic',
    inputs: ['task route', 'context budget', 'safety policy'],
    outputs: ['model selection', 'execution profile'],
    safety: ['provider credentials stay outside prompts', 'role-specific routing'],
    installable: !model.enabled,
  }))

  const mcps: CapabilityManifest[] = CLAW_MCP_SERVERS.map(server => ({
    id: `mcp-${server.id}`,
    kind: 'mcp',
    name: server.name,
    status:
      server.status === 'configured'
        ? 'installed'
        : server.status === 'discoverable'
          ? 'available'
          : server.status,
    trigger: `When ${server.exposes.slice(0, 2).join(' or ')} is required.`,
    purpose: `Expose ${server.exposes.join(', ')} through ${server.transport}.`,
    autonomy: server.status === 'configured' ? 'automatic' : 'approval-required',
    inputs: ['capability request'],
    outputs: server.exposes,
    safety: [server.trustBoundary],
    installable: server.status !== 'configured',
  }))

  return [...skills, ...models, ...toolCapabilities, ...mcps]
}

export function createExtensionPlan(
  input: ResearchInput,
  graph: ContextGraph,
): ExtensionPlan[] {
  const plan: ExtensionPlan[] = []

  if (graph.coverage.hasBenchmark || graph.coverage.hasExecutableProject) {
    plan.push({
      id: 'install-runner-adapter',
      title: 'Install experiment runner adapter',
      reason:
        'Benchmark or project code is present, so COG-CLAW needs executable install/train/eval hooks.',
      installs: ['mcp:experiment-runner', 'skill:reproduction-runner', 'tool:repair-loop'],
      guardrail: 'Runner commands are explicit, protocol files are locked and logs are immutable.',
      status: 'needs-approval',
    })
  }

  if (input.mode === 'follow-paper' || graph.coverage.hasPaper) {
    plan.push({
      id: 'install-source-browser',
      title: 'Enable browser evidence adapter',
      reason:
        'Paper, dataset or dependency claims need source verification beyond local context.',
      installs: ['mcp:browser', 'skill:browser-research', 'tool:source-snapshot'],
      guardrail: 'Every fetched source is cited, timestamped and treated as untrusted evidence.',
      status: 'ready',
    })
  }

  if (graph.coverage.modalities.some(modality => ['image', 'audio', 'video'].includes(modality))) {
    plan.push({
      id: 'install-multimodal-inspector',
      title: 'Add multimodal sample inspector',
      reason:
        'Rich media artifacts need modality-specific profiling before model or augmentation choices.',
      installs: ['skill:dataset-analysis', 'model:vision-context', 'tool:sample-inspector', 'tool:multimodal-analyze'],
      guardrail: 'Inspection produces data cards and never reads test labels for optimization.',
      status: 'ready',
    })
  }

  if (plan.length === 0) {
    plan.push({
      id: 'no-extension-needed',
      title: 'No extension required for current run',
      reason: 'The built-in controller, context graph and generator cover the current input.',
      installs: [],
      guardrail: 'Continue monitoring missing evidence and scaffold capabilities when needed.',
      status: 'ready',
    })
  }

  return plan
}
